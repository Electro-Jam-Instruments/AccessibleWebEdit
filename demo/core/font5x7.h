// cross-platform build uses HarfBuzz shaping + DirectWrite/CoreText/fontconfig
// (docs/11). What matters is the layout->pixels+a11y coupling, not the font.
//
// Any unmapped character renders as an open box ("tofu"), exactly like a real
// font with a missing glyph. Dependency-free beyond the STL.

