// Open-box fallback for unmapped characters.
inline const GlyphRows& TofuGlyph() {
  static const GlyphRows kTofu = {"#####", "#...#", "#...#", "#...#",
                                  "#...#", "#...#", "#####"};
  return kTofu;
}

inline const GlyphRows& GlyphFor(char c) {
  const auto& table = FontTable();
  auto it = table.find(c);
  return it == table.end() ? TofuGlyph() : it->second;
}

// True if column `col` (0=leftmost) of row `row` (0=top) is ink.
inline bool GlyphPixel(const GlyphRows& g, int row, int col) {
  return row >= 0 && row < 7 && col >= 0 && col < 5 && g[row][col] == '#';
}

